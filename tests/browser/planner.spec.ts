import {test,expect} from '@playwright/test';

test('source, preview, branch, month precision, geometry and sanitized library',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.locator('.map-pin').first()).toBeVisible();
 await expect(page.locator('#scenario')).toHaveValue('source-B');
 const original=(await page.locator('[data-stage="palau"]').textContent())!;
 await page.getByRole('button',{name:'Preview change',exact:true}).click();
 await expect(page.locator('#proposal')).toBeVisible();
 await expect(page.locator('[data-stage="palau"]')).toContainText('+21d');
 await page.getByLabel('Name this option').fill('Synthetic browser alternative');
 await page.getByRole('button',{name:'Save new option',exact:true}).click();
 await expect(page.locator('#notice')).toContainText('Saved a new draft');
 await expect(page.locator('#preview-state')).toHaveText('Saved draft');
 await page.locator('#scenario').selectOption('source-B');
 await expect(page.locator('[data-stage="palau"]')).toHaveText(original);
 await page.getByRole('button',{name:/H · FSM/}).click();
 await expect(page.locator('#date-basis')).toContainText('Month windows');
 await expect(page.getByRole('button',{name:'Preview change',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:/R · Raja/}).click();
 await page.getByText('Enter draft route coordinates', {exact:true}).click();
 await page.getByLabel('One longitude, latitude pair per line').fill('150, 0\n151, 1');
 await page.getByRole('button',{name:'Preview geometry',exact:true}).click();
 await expect(page.locator('#changes')).toContainText('Draft geometry updated');
 await page.getByRole('button',{name:'Discard preview',exact:true}).click();
 await page.getByRole('button',{name:'Sketch a route',exact:true}).click();
 await page.locator('#map').scrollIntoViewIfNeeded();
 const box=(await page.locator('#map').boundingBox())!;
 await page.mouse.click(box.x+100,box.y+150);
 await page.mouse.click(box.x+220,box.y+220);
 await page.mouse.click(box.x+330,box.y+170);
 await page.keyboard.press('Enter');
 await expect(page.locator('#proposal')).toBeVisible();
 await expect(page.locator('#changes')).toContainText('Draft geometry updated');
 await page.getByRole('button',{name:'Discard preview',exact:true}).click();
 await page.getByRole('button',{name:'Guides & documents',exact:true}).click();
 await page.getByLabel('Find a guide or document').fill('birding');
 await page.getByRole('button',{name:/Example Island Guide/}).click();
 await expect(page.locator('#document')).toContainText('Imported source revision');
 expect(await page.evaluate(()=>Boolean((window as unknown as {__sourceInjection?:boolean}).__sourceInjection))).toBe(false);
 await page.getByRole('button',{name:'Voyage plan',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await expect(page.locator('#map')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});
